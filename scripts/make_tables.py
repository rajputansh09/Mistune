"""Build report test-case tables (Lab format: ID, description/input, expected,
actual, result; failed cases highlighted) from results/full_results.json."""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = json.load(open(os.path.join(ROOT, "results", "full_results.json")))
rows = [r for r in rows if "test_oracle_validation" not in r["nodeid"]]


def esc(s, n=70):
    if s is None:
        return ""
    s = "".join(c if c.isprintable() or c == "\n" else f"\\x{ord(c):02x}" for c in str(s))
    s = s if len(s) <= n else s[: n - 1] + "…"
    s = s.replace("\\", "\\\\").replace("\n", "\\n").replace("|", "\\|").replace("`", "'")
    return "`" + s + "`" if s else "`(empty)`"


def section(r):
    p = r["nodeid"]
    if "/blackbox/" in p:
        return "Black-box"
    if "/whitebox/" in p:
        return "White-box"
    return "Integration"


out = ["# Appendix: test case tables (generated)\n",
       "Generated by `scripts/make_tables.py` from the latest full run. Rows marked **FAIL** "
       "are failed test cases; the defect ID refers to `docs/defects.md`.\n"]
for sec in ["Black-box", "White-box", "Integration"]:
    rs = [r for r in rows if section(r) == sec]
    out.append(f"\n## {sec} ({len(rs)} test cases)\n")
    out.append("| ID | Tech. | Description | Input | Expected | Actual | Result |")
    out.append("|---|---|---|---|---|---|---|")
    for r in rs:
        tid = r["id"]
        desc = r["description"]
        m = re.match(r"((?:BB|WB|TD|BU)-[A-Z]*-?\d+)\s+(.*)", desc)
        if m:
            tid, desc = m.group(1), m.group(2)
        if "[" in r["nodeid"] and not r["nodeid"].endswith(f"[{tid}]"):
            tid += " [" + r["nodeid"].split("[", 1)[1]
        verdict = r["verdict"]
        if verdict != "PASS":
            verdict = f"**{verdict}{' ' + r['defect'] if r.get('defect') else ''}**"
        out.append(f"| {tid} | {r['technique']} | {desc[:80]} | {esc(r['input'])} | "
                   f"{esc(r['expected'])} | {esc(r['actual'])} | {verdict} |")
open(os.path.join(ROOT, "docs", "test_case_tables.md"), "w").write("\n".join(out) + "\n")
print(len(rows), "rows")
