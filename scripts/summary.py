"""Collect results/*_metrics.json into one comparison table (results/summary.md)."""
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = []
for f in sorted(glob.glob(os.path.join(ROOT, "results", "*_metrics.json"))):
    m = json.load(open(f))
    v = m["verdicts"]
    rows.append(
        f"| {m['group']} | {m['test_cases']} | {v.get('PASS', 0)} | "
        f"{sum(c for k, c in v.items() if k.startswith('FAIL'))} | {m['statement_pct']} | {m['branch_pct']} | "
        f"{m['branch_pct_per_test']} | {m['redundancy_pct']} | "
        f"{m['oracle_valid']}/{m['oracle_checked']} | {', '.join(m['defects_or_failures']) or '-'} |"
    )
hdr = ("| Group | Cases | Pass | Fail | Stmt % | Branch % | Branch %/case | Redundancy % | "
       "Valid oracle | Defects / failures |\n|---|---|---|---|---|---|---|---|---|---|")
out = "# Group comparison (generated by scripts/summary.py)\n\n" + hdr + "\n" + "\n".join(rows) + "\n"
open(os.path.join(ROOT, "results", "summary.md"), "w").write(out)
print(out)
